"""Model registry tables.

The registry is the source of truth for which model artifact is loaded
for inference. Tables:

  * `atlas.model_versions`  — one row per trained artifact
  * `atlas.training_runs`   — log of training jobs (incl. failures)

Versions move through stages:
  staged → active → archived
The inference engine loads exactly the `active` row for each family.
Promotion is explicit and idempotent (POST `/v1/internal/models/promote`).
"""

from __future__ import annotations

import enum
from datetime import datetime, timezone
from uuid import UUID, uuid4

from sqlalchemy import JSON, DateTime, Enum, Float, ForeignKey, Index, Integer, String
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.dialects.postgresql import UUID as PgUUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

# migrations/sql/0003_create_odds_ticks.sql declares `payload` as JSONB
# (GIN-indexable, containment-queryable) — the plain generic JSON type
# below would silently drift from that on a real Postgres deployment.
# with_variant renders as JSONB on postgres, plain JSON on sqlite (JSONB
# has no sqlite compiler support at all — Base.metadata.create_all
# against the sqlite-backed test suite would hard-fail otherwise).
_JSONB_ON_POSTGRES = JSON().with_variant(JSONB, "postgresql")

from atlas.registry.base import Base


class ModelFamily(str, enum.Enum):
    anomaly = "anomaly"            # IsolationForest
    cluster = "cluster"            # KMeans (stable IDs)
    density = "density"            # HDBSCAN
    classifier = "classifier"      # XGBoost
    ranker = "ranker"              # LightGBM
    similarity = "similarity"      # historical nearest-neighbour index


class ModelStage(str, enum.Enum):
    staged = "staged"
    active = "active"
    archived = "archived"


class LabelSource(str, enum.Enum):
    """Where the training labels for this model version came from.

    Sprint 0 mandates "clear separation between candidate bot signals
    and confirmed events". Same rule applies to labels themselves:
    bootstrap-rule labels are a candidate signal, not ground truth,
    and the operator promoting a model must SEE that distinction.

    `none`              — model is unsupervised (anomaly, cluster, density)
    `bootstrap_rule`    — labels generated by the deterministic rule in
                          atlas.models.classifier.bootstrap_labels.
                          Models trained this way are essentially the
                          rule with XGBoost noise; treat as candidate
                          until refit with real labels.
    `historical_outcome` — labels derived from observed match outcomes
                          (the post-V1 path once enough history exists).
    `human_curated`     — labels assigned by an analyst.
    """

    none = "none"
    bootstrap_rule = "bootstrap_rule"
    historical_outcome = "historical_outcome"
    human_curated = "human_curated"


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


