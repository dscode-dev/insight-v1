class OddsTickRow(Base):
    """One persisted odds snapshot — the first-class odds-history row.

    Every `match.odds` canonical event Atlas consumes is appended here
    as its own row; we DO NOT keep only the latest snapshot. The full
    temporal evolution of every (match, market, bookmaker) lane is
    reconstructable by ordering on `captured_at`.

    Idempotency: `canonical_event_id` is unique. Re-delivery of the
    same canonical event (consumer reclaim/replay) is a no-op insert,
    so history never double-counts a snapshot.
    """

    __tablename__ = "odds_ticks"
    __table_args__ = (
        # Name matches migrations/sql/0003_create_odds_ticks.sql exactly
        # — create_all() against an already-migrated Postgres (or a
        # second create_all() call anywhere) must not create a
        # redundant duplicate index under a different name.
        Index("ix_odds_ticks_match_market_captured", "match_id", "market", "captured_at"),
        {"schema": "atlas"},
    )

    id: Mapped[UUID] = mapped_column(PgUUID(as_uuid=True), primary_key=True, default=uuid4)
    # The Hub's canonical event id — unique idempotency key.
    canonical_event_id: Mapped[UUID] = mapped_column(
        PgUUID(as_uuid=True), unique=True, index=True
    )
    provider: Mapped[str] = mapped_column(String(64))
    competition_id: Mapped[UUID | None] = mapped_column(
        PgUUID(as_uuid=True), nullable=True
    )
    # Stable per-match grouping key (payload.match_id) — NOT the
    # snapshot-scoped canonical match_id.
    match_id: Mapped[UUID] = mapped_column(PgUUID(as_uuid=True), index=True)
    market: Mapped[str] = mapped_column(String(32))
    bookmaker: Mapped[str] = mapped_column(String(64))
    home: Mapped[float | None] = mapped_column(Float, nullable=True)
    draw: Mapped[float | None] = mapped_column(Float, nullable=True)
    away: Mapped[float | None] = mapped_column(Float, nullable=True)
    captured_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), index=True)
    # Full normalized payload — preserves outcomes for non-h2h markets
    # + any provider fields beyond the foundational home/draw/away.
    payload: Mapped[dict] = mapped_column(_JSONB_ON_POSTGRES, default=dict)
    ingested_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=_utcnow
    )


